export const LAND_W = 72
export const LAND_H = 36

/** Bytes da textura R8 (0 = mar, 255 = terra), linha 0 no polo norte. */
export function landMask(): Uint8Array {
  const data = new Uint8Array(LAND_W * LAND_H)
  BANDS.forEach((ranges, row) => {
    for (const [from, to] of ranges) for (let c = from; c <= to; c++) data[row * LAND_W + c] = 255
  })
  return data
}
